export async function seed36Bikes(db?: mongoose.mongo.Db) {
  let createdConnection = false;
  let database = db;

  if (!database) {
    const mongoUri =
      process.env.MONGO_URI ||
      'mongodb+srv://raxwotechnology_db_user:0Bk8CNwvPAenfq1y@cluster0.nziv5e7.mongodb.net/?retryWrites=true&w=majority';

    console.log('Connecting to database for 36 bikes seed...');
    await mongoose.connect(mongoUri);
    database = mongoose.connection.db!;
    createdConnection = true;
  }

  const branchesColl = database.collection('branches');
  const vehiclesColl = database.collection('vehicles');
  const now = new Date();

  // Find or create default showroom branch: MANTHUSA TVS - Weliweriya Showroom
  let branch = await branchesColl.findOne({ name: /Weliweriya/i });
  if (!branch) {
    branch = await branchesColl.findOne({});
  }
  const branchId = branch?._id;
  const branchName = branch?.name || 'MANTHUSA TVS - Weliweriya Showroom';

  console.log(`Seeding 36 TVS Bikes into branch: ${branchName} (${branchId})...`);

  let count = 0;
  for (const bike of tvsBikesCatalog) {
    const { stockQty, ...bikeData } = bike;
    const bikeDoc = {
      ...bikeData,
      branch: branchId,
      location: branchId,
      branchStock: [
        {
          branchId: branchId,
          branchName: branchName,
          quantity: stockQty || 1,
          availableColors: [bike.color],
        },
      ],
      updatedAt: now,
    };

    await vehiclesColl.findOneAndUpdate(
      { stockNumber: bike.stockNumber },
      {
        $set: bikeDoc,
        $setOnInsert: { createdAt: now },
      },
      { upsert: true, returnDocument: 'after' }
    );
    count++;
    console.log(
      `✓ [${count}/36] Seeded TVS Bike: ${bike.model} (${bike.variant}) | Price: Rs. ${bike.sellingPrice.toLocaleString()} | Round: ${bike.roundNumber} | Chassis: ${bike.chassisNumber} | Engine: ${bike.engineNumber}`
    );
  }

  console.log(`\n🎉 Successfully seeded all ${count} TVS bikes with complete 100% technical specifications and stock details!`);

  if (createdConnection) {
    await mongoose.disconnect();
    console.log('Disconnected from database.');
  }
}

